# 17. Шестерні — повільний, але очевидно правильний розв'язок.
# НСД — перебором усіх можливих дільників; кількість зачеплень — прямою
# симуляцією шестерень, як в умові. Час O(a·b) у найгіршому випадку.
# Використовується для стрес-тестування еталону на малих випадкових тестах.
a, b = map(int, input().split())

g = max(d for d in range(1, min(a, b) + 1) if a % d == 0 and b % d == 0)

# Зубці кожної шестерні пронумеровано від 0; позначені зубці мають номер 0.
# За одне зачеплення кожна шестерня повертається рівно на один зубець.
p1, p2, steps = 0, 0, 0
while True:
    p1 = (p1 + 1) % a
    p2 = (p2 + 1) % b
    steps += 1
    if p1 == 0 and p2 == 0:
        break
print(g, steps)
