# 26. Рейтинг — повільний, але очевидно правильний розв'язок: O(n²).
# Правило з умови записано окремою функцією, а рейтинг будується «вибором»:
# щоразу шукаємо найкращого серед ще не розставлених учасників.
# Використовується для стрес-тестування еталону на малих випадкових тестах.
import sys


def higher(a, b):
    """Чи стоїть учасник a у рейтингу вище за учасника b? a і b — трійки (s, t, номер)."""
    if a[0] != b[0]:
        return a[0] > b[0]  # більше балів — вище
    if a[1] != b[1]:
        return a[1] < b[1]  # за рівних балів менший штрафний час — вище
    return a[2] < b[2]      # за рівних балів і часу менший номер — вище


data = sys.stdin.read().split()
n = int(data[0])
left = [(int(data[2 * i - 1]), int(data[2 * i]), i) for i in range(1, n + 1)]
order = []
while left:
    best = left[0]
    for p in left:
        if higher(p, best):
            best = p
    order.append(best[2])
    left.remove(best)
print(*order)
