# 25. Плитки — еталонний розв'язок (перебір дільників до √n парами).
# Час O(√n), пам'ять O(1).
import math

n = int(input())

count = 0  # кількість прямокутників = кількість дільників n
best = 1   # найбільший дільник, що не перевищує √n
# math.isqrt(n) — точна ціла частина кореня без похибок дійсних чисел.
# Цикл for по range у Python помітно швидший за while з i * i <= n.
for i in range(1, math.isqrt(n) + 1):
    if n % i == 0:
        # пара дільників i і n // i: прямокутники i × (n // i) і (n // i) × i
        if i * i == n:
            count += 1  # точний квадрат: i × i — один прямокутник, а не два
        else:
            count += 2
        best = i  # i зростає, тож наприкінці тут найближчий до √n дільник

print(count)
print(2 * (best + n // best))
