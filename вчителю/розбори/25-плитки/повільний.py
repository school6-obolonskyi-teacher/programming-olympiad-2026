# 25. Плитки — повільний, але очевидно правильний розв'язок: O(n).
# Перебираємо кількість рядів a від 1 до n. Якщо n ділиться на a, то
# прямокутник a × (n / a) можна викласти; рахуємо його і його периметр.
# Використовується для стрес-тестування еталону на малих випадкових тестах.
n = int(input())
count = 0
best = None
for a in range(1, n + 1):
    if n % a == 0:
        b = n // a
        count += 1
        p = 2 * (a + b)
        if best is None or p < best:
            best = p
print(count)
print(best)
