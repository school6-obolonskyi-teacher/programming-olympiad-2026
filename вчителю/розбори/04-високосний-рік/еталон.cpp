// 04. Високосний рік — еталонний розв'язок.
// Час O(1), пам'ять O(1).
#include <bits/stdc++.h>
using namespace std;

int main() {
    long long y;  // y ≤ 10⁹ уміщується й в int
    cin >> y;
    // Високосний: ділиться на 400, АБО ділиться на 4 І не ділиться на 100.
    // Дужки не обов'язкові (&& виконується раніше за ||), але так зрозуміліше.
    if (y % 400 == 0 || (y % 4 == 0 && y % 100 != 0))
        cout << 366 << '\n';
    else
        cout << 365 << '\n';
    return 0;
}
