# 04. Високосний рік — незалежна перевірка вбудованим календарем Python.
# Модуль datetime використовує григоріанський календар, продовжений на всі роки
# (як і в умові). Номер дня 31 грудня в році — це і є кількість днів у році.
# datetime працює лише з роками від 1 до 9999, тому розв'язок годиться
# тільки для стрес-тесту (генератор без параметрів дає саме такі роки).
import datetime

y = int(input())
print(datetime.date(y, 12, 31).timetuple().tm_yday)
