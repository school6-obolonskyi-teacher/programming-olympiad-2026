# 02. Годинник — еталонний розв'язок.
t = int(input())
s = t % 60            # секунди, що лишилися після повних хвилин
m = t // 60 % 60      # повні хвилини без повних годин
h = t // 3600 % 24    # повні години без повних діб
# {m:02d} — щонайменше дві цифри з провідним нулем; години — без нього
print(f"{h}:{m:02d}:{s:02d}")
