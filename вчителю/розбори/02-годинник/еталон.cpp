// 02. Годинник — еталонний розв'язок.
// Час O(1), пам'ять O(1).
#include <bits/stdc++.h>
using namespace std;

int main() {
    long long t;  // t ≤ 10⁹ уміщується й в int, але long long не завадить
    cin >> t;
    int s = t % 60;              // секунди, що лишилися після повних хвилин
    int m = t / 60 % 60;         // повні хвилини без повних годин
    int h = t / 3600 % 24;       // повні години без повних діб
    // Хвилини й секунди менші за 60, тому їх можна вивести двома цифрами:
    // цифра десятків (m / 10) і цифра одиниць (m % 10). Так провідний нуль
    // з'являється сам, без if. Інший спосіб: printf("%d:%02d:%02d\n", h, m, s).
    cout << h << ':' << m / 10 << m % 10 << ':' << s / 10 << s % 10 << '\n';
    return 0;
}
