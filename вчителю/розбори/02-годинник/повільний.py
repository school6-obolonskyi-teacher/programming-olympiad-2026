# 02. Годинник — повільний, але очевидно правильний розв'язок:
# «прокручуємо» годинник на одну секунду t разів, як справжній годинник.
# Годиться лише для невеликих t (такі створює генератор без параметрів).
t = int(input())
h = m = s = 0
for _ in range(t):
    s += 1
    if s == 60:
        s = 0
        m += 1
        if m == 60:
            m = 0
            h += 1
            if h == 24:
                h = 0


def two(x):
    return "0" + str(x) if x < 10 else str(x)


print(str(h) + ":" + two(m) + ":" + two(s))
