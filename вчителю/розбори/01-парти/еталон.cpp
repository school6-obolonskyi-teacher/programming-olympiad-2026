// 01. Парти — еталонний розв'язок: ділення з округленням угору без if.
// Час O(1), пам'ять O(1).
#include <bits/stdc++.h>
using namespace std;

int main() {
    // n + k - 1 може сягати 2e9 + 2e9 - 1 ≈ 4·10⁹ > 2³¹ - 1 ≈ 2,1·10⁹, тому long long.
    long long n, k;
    cin >> n >> k;
    // Додаємо k - 1: якщо n кратне k, частка не зміниться,
    // а якщо остача від 1 до k - 1, частка збільшиться рівно на 1.
    cout << (n + k - 1) / k << '\n';
    return 0;
}
