# 01. Парти — повільний, але очевидно правильний розв'язок.
# Ставимо парти по одній, доки всім учням не вистачить місць.
# Кількість кроків дорівнює відповіді, тому годиться лише для тестів,
# де n / k невелике (такі створює генератор без параметрів).
n, k = map(int, input().split())
desks = 0
places = 0
while places < n:
    desks += 1
    places += k
print(desks)
