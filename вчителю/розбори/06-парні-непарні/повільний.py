# 06. Парні та непарні — простий, очевидно правильний розв'язок для стрес-тестування.
# Парність числа визначаємо за його модулем: x і |x| мають однакову парність.
n = int(input())
a = list(map(int, input().split()))
even = 0
odd = 0
for x in a:
    if abs(x) % 2 == 0:
        even += 1
    else:
        odd += 1
print(even, odd)
