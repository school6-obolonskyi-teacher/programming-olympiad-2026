# 21. Сходинки — еталонний розв'язок (динамічне програмування).
# dp[i] — найменша енергія, щоб дійти зі сходинки 1 до сходинки i (індекси з 0).
# Час O(n), пам'ять O(n). Цикл замість рекурсії: глибина рекурсії n = 2·10^5
# у Python перевищує стандартне обмеження (1000 викликів).
import sys


def main():
    data = sys.stdin.buffer.read().split()  # швидке читання всього входу одразу
    n = int(data[0])
    c = list(map(int, data[1:n + 1]))

    dp = [0] * n
    dp[0] = c[0]          # база: учень уже стоїть на першій сходинці і платить за неї
    dp[1] = c[0] + c[1]   # на другу сходинку можна потрапити лише з першої
    for i in range(2, n):
        # на сходинку i приходять або з i−1 (крок на 1), або з i−2 (крок на 2)
        dp[i] = c[i] + min(dp[i - 1], dp[i - 2])
    print(dp[n - 1])


main()
