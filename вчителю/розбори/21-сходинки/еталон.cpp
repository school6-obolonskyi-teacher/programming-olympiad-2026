// 21. Сходинки — еталонний розв'язок (динамічне програмування).
// dp[i] — найменша енергія, щоб дійти зі сходинки 1 до сходинки i (ціни обох сплачено).
// Час O(n), пам'ять O(n).
#include <bits/stdc++.h>
using namespace std;

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int n;
    cin >> n;
    vector<int> c(n + 1);
    for (int i = 1; i <= n; i++) cin >> c[i];

    // Оцінка: шлях 1, 3, 5, … містить не більше n/2 + 2 сходинок, тому
    // dp[i] ≤ (10^5 + 2) · 10^4 ≈ 1,00002·10^9 < 2^31 − 1, і int достатньо.
    vector<int> dp(n + 1);
    dp[1] = c[1];         // база: учень уже стоїть на сходинці 1 і платить за неї
    dp[2] = c[1] + c[2];  // на сходинку 2 можна потрапити лише зі сходинки 1
    for (int i = 3; i <= n; i++) {
        // на сходинку i приходять або з i−1 (крок на 1), або з i−2 (крок на 2)
        dp[i] = c[i] + min(dp[i - 1], dp[i - 2]);
    }
    cout << dp[n] << '\n';
    return 0;
}
