# 05. Сума цифр — еталонний розв'язок.
# Час O(кількість цифр) = O(log N), пам'ять O(1).
# Цілі числа в Python не мають верхньої межі, тому N ≤ 10^18 не потребує окремого типу.
import sys

n = int(sys.stdin.readline())
total = 0
while n > 0:
    total += n % 10  # остання цифра
    n //= 10         # відкидаємо останню цифру (саме //, а не /)
print(total)
