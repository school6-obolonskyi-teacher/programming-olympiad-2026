// 05. Сума цифр — еталонний розв'язок.
// Час O(кількість цифр) = O(log N), пам'ять O(1).
#include <bits/stdc++.h>
using namespace std;

int main() {
    // N ≤ 10^18 не вміщується в int (≤ 2 147 483 647), але вміщується в long long (≤ 9,2·10^18).
    long long n;
    cin >> n;

    // Сума цифр не більша за 9 · 18 = 162, тому для неї достатньо int.
    int sum = 0;
    while (n > 0) {
        sum += n % 10;  // остання цифра
        n /= 10;        // відкидаємо останню цифру
    }
    cout << sum << '\n';
    return 0;
}
