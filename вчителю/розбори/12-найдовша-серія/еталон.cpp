// 12. Найдовша серія — еталонний розв'язок: один прохід масивом.
// Час O(n), пам'ять O(1) (масив навіть не потрібно зберігати).
#include <bits/stdc++.h>
using namespace std;

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int n;
    cin >> n;
    int prev;            // |aᵢ| ≤ 10⁹ уміщується в int
    cin >> prev;
    int cur = 1;         // довжина серії, що закінчується на поточному елементі
    int best = 1;        // n ≥ 1, тож серія довжини 1 є завжди
    for (int i = 1; i < n; i++) {
        int x;
        cin >> x;
        if (x == prev)
            cur++;       // серія продовжується
        else
            cur = 1;     // почалася нова серія з одного числа
        // Оновлюємо відповідь на КОЖНОМУ кроці, а не лише при обриві серії:
        // інакше пропустимо серію, що закінчується разом із масивом.
        best = max(best, cur);
        prev = x;
    }
    cout << best << '\n';
    return 0;
}
