# 15. Дужки — повільний, але очевидно правильний розв'язок: O(n²).
# Ідея, незалежна від стека: у правильній послідовності завжди є дві сусідні
# дужки-пара — "()", "[]" або "{}". Викреслюємо такі пари, доки можна.
# Послідовність правильна тоді й лише тоді, коли в результаті рядок стане порожнім.
# Використовується для стрес-тестування еталону на малих випадкових тестах.
s = input().strip()
changed = True
while changed:
    changed = False
    for pair in ("()", "[]", "{}"):
        if pair in s:
            s = s.replace(pair, "")
            changed = True
print("YES" if s == "" else "NO")
