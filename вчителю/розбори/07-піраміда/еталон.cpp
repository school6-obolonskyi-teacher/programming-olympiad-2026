// 07. Піраміда — еталонний розв'язок (вкладені цикли).
// Час O(N²): усього виводиться 1 + 2 + … + N = N(N+1)/2 чисел; пам'ять O(1).
#include <bits/stdc++.h>
using namespace std;

int main() {
    int n;
    cin >> n;
    for (int i = 1; i <= n; i++) {        // зовнішній цикл: номер рядка
        for (int j = 1; j <= i; j++) {    // внутрішній цикл: числа 1..i у рядку i
            cout << j;
            if (j < i) cout << ' ';       // пробіл лише МІЖ числами
        }
        cout << '\n';                     // кінець рядка після внутрішнього циклу
    }
    return 0;
}
