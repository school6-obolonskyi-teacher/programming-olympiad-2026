# 07. Піраміда — еталонний розв'язок (вкладені цикли).
# Час O(N²), пам'ять O(N) на один рядок.
n = int(input())
for i in range(1, n + 1):          # зовнішній цикл: номер рядка
    parts = []
    for j in range(1, i + 1):      # внутрішній цикл: числа 1..i
        parts.append(str(j))
    print(" ".join(parts))         # join ставить пробіли лише між числами
