# 07. Піраміда — чекер: порівнює відповідь РЯДОК ЗА РЯДКОМ.
# Використання: python чекер.py вхід вихід_учасника правильний_вихід ; код 0 — правильно.
#
# Правильна відповідь тут одна, але в цій задачі важить форма виведення: кожен рядок
# піраміди має бути окремим рядком. Звичайне порівняння за токенами (як у
# інструменти/перевірити.py без чекера) прийняло б усі числа в одному рядку.
# Тому чекер діє як стандартний чекер lcmp із бібліотеки testlib:
#   * рядки (крім порожніх у самому кінці) і числа в кожному рядку мають збігатися;
#   * кількість пробілів між числами, пробіли в кінці рядка і порожні рядки
#     в самому кінці виведення не важать.
import sys


def read_lines(path):
    with open(path, encoding="utf-8", errors="replace") as f:
        lines = [line.split() for line in f.read().splitlines()]
    while lines and not lines[-1]:  # порожні рядки в кінці не важать
        lines.pop()
    return lines


def main():
    _, _inp, got, expected = sys.argv
    sys.exit(0 if read_lines(got) == read_lines(expected) else 1)


main()
