# 10. Паліндром — простий, очевидно правильний розв'язок для стрес-тестування.
# Перевіряємо означення: для кожної позиції i символ дорівнює символу на дзеркальній позиції n-1-i.
s = input().strip()
n = len(s)
ok = True
for i in range(n):
    if s[i].lower() != s[n - 1 - i].lower():
        ok = False
print("YES" if ok else "NO")
