// 03. Трикутник — еталонний розв'язок.
// Час O(1), пам'ять O(1).
#include <bits/stdc++.h>
using namespace std;

int main() {
    // Сума двох сторін може сягати 2e9 + 2e9 = 4·10⁹ > 2³¹ - 1 ≈ 2,1·10⁹, тому long long.
    long long a, b, c;
    cin >> a >> b >> c;
    // Кожна сторона має бути СТРОГО меншою за суму двох інших:
    // при рівності трикутник «плаский» і має нульову площу.
    if (a + b > c && a + c > b && b + c > a)
        cout << "YES\n";
    else
        cout << "NO\n";
    return 0;
}
