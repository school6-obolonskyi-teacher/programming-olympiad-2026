# 03. Трикутник — незалежна перевірка через формулу Герона.
# Для трикутника зі сторонами a, b, c квадрат площі S задовольняє рівність
#     16·S² = (a + b + c)(−a + b + c)(a − b + c)(a + b − c).
# Трикутник з ненульовою площею існує тоді й лише тоді, коли всі три останні
# множники додатні. Від'ємними одночасно два множники бути не можуть
# (їхня сума дорівнювала б 2a, 2b або 2c > 0), тож достатньо перевірити,
# що добуток додатний. Python рахує з довгими цілими, переповнення немає.
a, b, c = map(int, input().split())
p = (a + b + c) * (-a + b + c) * (a - b + c) * (a + b - c)
print("YES" if p > 0 else "NO")
