# 08. Фібоначчі — еталонний розв'язок (ітеративно, два останні числа).
# Час O(N), пам'ять O(N) на список для виведення.
# Цілі числа в Python не переповнюються, тож тип даних обирати не треба.
n = int(input())
a, b = 0, 1  # a = F(i), b = F(i+1)
result = []
for _ in range(n):
    result.append(a)
    a, b = b, a + b
print(" ".join(map(str, result)))
