# 20. Цукерки навпіл — еталонний розв'язок (перебір усіх 2^n розподілів).
# Час O(2^n), пам'ять O(2^n): при n = 20 це 1 048 576 сум, близько 75 МБ у Python.
#
# Рекурсивний перебір, як в еталон.cpp, у Python робить понад 2 мільйони викликів
# функції; при n = 20 у наших вимірюваннях він працював 0,3–0,8 с — вкладається
# в 1 с, але із малим запасом. Тому тут список усіх сум підмножин будується
# ітеративно (0,2–0,5 с): після обробки k пакетиків список містить 2^k сум,
# а кожен новий пакетик подвоює список («без нього» — старі суми,
# «з ним» — старі суми + pᵢ). Цикл і генератори списків у Python набагато
# дешевші за виклики функцій.
import sys


def main():
    data = sys.stdin.buffer.read().split()
    n = int(data[0])
    p = list(map(int, data[1:n + 1]))
    total = sum(p)

    sums = [0]  # суми цукерок першого друга для всіх розподілів уже розглянутих пакетиків
    for x in p:
        sums += [s + x for s in sums]

    # Першому другові дістається s, другому total − s; різниця |total − 2s|.
    print(min(abs(total - 2 * s) for s in sums))


main()
